"""Import Jeff Weeks's group artwork, preserving paths/pixels. Requires fonttools."""
from pathlib import Path
import re,shutil,json,xml.etree.ElementTree as ET
from fontTools.pens.boundsPen import BoundsPen
from fontTools.svgLib.path import parse_path
root=Path(__file__).resolve().parents[2]
assets=root/'upstream/Source - SwiftUI/KaleidoPaint/KaleidoPaintAssets.xcassets'
res=root/'app/src/main/res';(res/'drawable').mkdir(exist_ok=True)
enums=re.findall(r'(wpg\w+)\s*\("([^"]+)"\)',(root/'geometry/src/main/kotlin/com/cinderblocksoftware/kaleidopaint/geometry/WallpaperGroup.kt').read_text())
code=['// Artwork from KaleidoPaint, © 2026 Jeff Weeks, GPLv2+.', '// Android port © 2026 Cinderblock Software, GPLv3+. See LICENSE.', '// Generated by tools/port/import_editor_artwork.py.','package com.cinderblocksoftware.kaleidopaint','import com.cinderblocksoftware.kaleidopaint.geometry.WallpaperGroup', 'internal fun groupArtwork(group: WallpaperGroup, toolbar: Boolean): Int = when (group) {']
for enum,raw in enums:
 name=enum.lower();folder=assets/'wallpaper group panel buttons'/f'{raw}.imageset'
 imgs=json.loads((folder/'Contents.json').read_text())['images'];image=next(i['filename'] for i in imgs if i['scale']=='3x')
 shutil.copyfile(folder/image,res/'drawable-nodpi'/f'group_panel_{name}.png')
 svg=assets/'wallpaper group toolbar buttons'/f'{raw}.symbolset'/f'{raw}.svg'
 g=next(n for n in ET.parse(svg).getroot().iter() if n.attrib.get('id')=='Regular-M')
 paths=[n.attrib['d'] for n in g.iter() if n.tag.endswith('}path')]
 pen=BoundsPen(None)
 for p in paths:parse_path(p,pen)
 x0,y0,x1,y1=pen.bounds;side=max(x1-x0,y1-y0)*1.08
 x=(x0+x1-side)/2;y=(y0+y1-side)/2
 v=ET.Element('vector',{'xmlns:android':'http://schemas.android.com/apk/res/android','android:width':'32dp','android:height':'32dp','android:viewportWidth':str(side),'android:viewportHeight':str(side)})
 group=ET.SubElement(v,'group',{'android:translateX':str(-x),'android:translateY':str(-y)})
 for p in paths:ET.SubElement(group,'path',{'android:fillColor':'#000000','android:pathData':p})
 ET.indent(v)
 (res/'drawable'/f'group_toolbar_{name}.xml').write_text('<?xml version="1.0" encoding="utf-8"?>\n<!-- Original paths © Jeff Weeks, GPLv2+; Android conversion GPLv3+. -->\n'+ET.tostring(v,encoding='unicode')+'\n')
 code.append(f'    WallpaperGroup.{enum} -> if (toolbar) R.drawable.group_toolbar_{name} else R.drawable.group_panel_{name}')
# Jeff's custom paint-bucket symbol is reusable too; standard action icons are
# independently drawn on Android rather than copied from Apple's system font.
svg=assets/'paint bucket.symbolset'/'paint bucket.svg'
g=next(n for n in ET.parse(svg).getroot().iter() if n.attrib.get('id')=='Regular-M')
paths=[n.attrib['d'] for n in g.iter() if n.tag.endswith('}path')]
pen=BoundsPen(None)
for p in paths:parse_path(p,pen)
x0,y0,x1,y1=pen.bounds;side=max(x1-x0,y1-y0)*1.08
v=ET.Element('vector',{'xmlns:android':'http://schemas.android.com/apk/res/android','android:width':'32dp','android:height':'32dp','android:viewportWidth':str(side),'android:viewportHeight':str(side)})
group=ET.SubElement(v,'group',{'android:translateX':str(-(x0+x1-side)/2),'android:translateY':str(-(y0+y1-side)/2)})
for p in paths:ET.SubElement(group,'path',{'android:fillColor':'#000000','android:pathData':p})
ET.indent(v)
(res/'drawable/editor_paint_bucket.xml').write_text('<?xml version="1.0" encoding="utf-8"?>\n<!-- Original paths © Jeff Weeks, GPLv2+; Android conversion GPLv3+. -->\n'+ET.tostring(v,encoding='unicode')+'\n')
code+=['}',''];(root/'app/src/main/java/com/cinderblocksoftware/kaleidopaint/GroupArtwork.kt').write_text('\n'.join(code))
print('Imported',len(enums),'original group icons and illustrations')
